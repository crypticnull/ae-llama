#!/usr/bin/env node
/*
 * test-enum-fixture-drift.js — the vendor-enum fixture must name its build,
 * and comfy-install.js must say when the installed build is a different one
 * (WORKPLAN §17l, NEXT UP 27).
 *
 * tests/fixtures/comfy-core-enums.json is a hand-taken snapshot, and the
 * installer downloads /releases/latest, so the build it describes moves
 * without the repo changing. Nothing forced a refresh. This pins the three
 * pieces that now do: the fixture carries a real version, the harvester
 * refuses to write one without it, and the installer runs the drift check.
 * No backend, no network.
 */
"use strict";

const fs = require("fs");
const os = require("os");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const drift = require(path.join(ROOT, "scripts", "lib", "enum-fixture-drift.js"));

let failed = 0, passed = 0;
function check(ok, label, detail) {
  if (ok) { passed++; console.log("ok   - " + label); }
  else { failed++; console.log("FAIL - " + label + (detail ? "\n       " + detail : "")); }
}

// 1. The committed fixture names a real version, not "unknown".
const fv = drift.fixtureVersion();
check(/^\d+\.\d+\.\d+/.test(String(fv)),
  "the committed fixture records a numeric comfyuiVersion", "got " + fv);

// 2. The vendor file's real shape parses; junk does not.
const vendorText = "# This file is automatically generated by the build process when version is\n" +
  "# updated in pyproject.toml.\n__version__ = \"0.34.0\"\n";
check(drift.parseVersionPy(vendorText) === "0.34.0",
  "comfyui_version.py as the vendor build writes it parses to 0.34.0");
check(drift.parseVersionPy("version = 1") === null && drift.parseVersionPy("") === null,
  "text without __version__ parses to null");

// 3. installedVersion reads the file beside main.py, and a missing one is null.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "aell-enumdrift-"));
try {
  fs.writeFileSync(path.join(tmp, "main.py"), "");
  check(drift.installedVersion(path.join(tmp, "main.py")) === null,
    "no comfyui_version.py -> installedVersion null");
  fs.writeFileSync(path.join(tmp, "comfyui_version.py"), vendorText.replace("0.34.0", "0.35.1"));
  check(drift.installedVersion(path.join(tmp, "main.py")) === "0.35.1",
    "installedVersion reads comfyui_version.py beside main.py");
  fs.writeFileSync(path.join(tmp, "f.json"), JSON.stringify({ comfyuiVersion: "unknown" }));
  check(drift.fixtureVersion(path.join(tmp, "f.json")) === null,
    "a fixture recording \"unknown\" has no version");
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

// 4. driftNote: silent only on an exact match; every other case says so.
check(drift.driftNote("0.34.0", "0.34.0") === null, "same build -> no note");
const moved = drift.driftNote("0.34.0", "0.35.1") || "";
check(/0\.35\.1/.test(moved) && /0\.34\.0/.test(moved) &&
      /harvest-core-enums\.js/.test(moved),
  "a different build names both versions and the re-harvest command", moved);
check(/UNKNOWN/.test(drift.driftNote("0.34.0", null) || ""),
  "an unreadable installed version is reported, not treated as a match");
check(/harvest-core-enums\.js/.test(drift.driftNote(null, "0.34.0") || ""),
  "a fixture with no version asks for a re-harvest");

// 5. Wiring: the installer runs the check; the harvester refuses no version.
const install = fs.readFileSync(path.join(ROOT, "scripts", "comfy-install.js"), "utf8");
check(/require\("\.\/lib\/enum-fixture-drift\.js"\)/.test(install) &&
      /driftNote\(/.test(install),
  "comfy-install.js runs the drift check");
const harvest = fs.readFileSync(path.join(ROOT, "scripts", "harvest-core-enums.js"), "utf8");
check(!/\|\| "unknown"/.test(harvest) && /if \(!version\)/.test(harvest),
  "harvest-core-enums.js refuses to write a fixture with no version");

console.log("\n" + passed + " passed, " + failed + " failed");
process.exit(failed ? 1 : 0);
