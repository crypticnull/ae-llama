/*
 * enum-fixture-drift.js — say when tests/fixtures/comfy-core-enums.json was
 * taken from a different ComfyUI than the one installed (WORKPLAN §17l).
 *
 * The fixture is a hand-taken snapshot of the vendor build's enum values,
 * and bootstrapComfy downloads /releases/latest, so the build a user gets
 * moves without anyone touching the repo. A stale fixture fails safe one
 * way (it rejects a value a newer build added) and UNSAFE the other (it
 * passes a value the newer build dropped — the res_2s failure of §17f).
 * Nothing forced a refresh; this is the check that names it, at the one
 * moment a new build lands on a machine that can re-harvest it.
 *
 * The installed version is read from ComfyUI/comfyui_version.py beside
 * main.py (generated by the vendor build, `__version__ = "0.34.0"`), so
 * no backend has to be running to answer.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const FIXTURE = path.join(__dirname, "..", "..", "tests", "fixtures",
                          "comfy-core-enums.json");

function parseVersionPy(text) {
  const m = /^__version__\s*=\s*["']([^"']+)["']/m.exec(String(text || ""));
  return m ? m[1] : null;
}

function installedVersion(mainPy) {
  if (!mainPy) return null;
  try {
    return parseVersionPy(fs.readFileSync(
      path.join(path.dirname(mainPy), "comfyui_version.py"), "utf8"));
  } catch (e) { return null; }
}

function fixtureVersion(file) {
  try {
    const v = JSON.parse(fs.readFileSync(file || FIXTURE, "utf8"))
      .comfyuiVersion;
    return (typeof v === "string" && v && v !== "unknown") ? v : null;
  } catch (e) { return null; }
}

const REHARVEST =
  "node scripts/comfy-install.js --boot && " +
  "node scripts/harvest-core-enums.js --url <the managed url>, " +
  "then node tests/test-comfy-enum-values.js";

/* null when they match; otherwise one sentence naming both versions and
 * the re-harvest command. An unreadable side is reported, never assumed
 * equal — "could not tell" must not read as "no drift". */
function driftNote(fixtureVer, installedVer) {
  if (fixtureVer && installedVer && fixtureVer === installedVer) return null;
  if (!installedVer) {
    return "could not read the installed ComfyUI version " +
      "(comfyui_version.py), so whether tests/fixtures/comfy-core-enums.json " +
      "(taken from " + (fixtureVer || "an unknown version") +
      ") still matches it is UNKNOWN";
  }
  if (!fixtureVer) {
    return "tests/fixtures/comfy-core-enums.json records no ComfyUI " +
      "version, so it cannot be checked against the installed " +
      installedVer + ". Re-harvest: " + REHARVEST;
  }
  return "the installed ComfyUI is " + installedVer + " but " +
    "tests/fixtures/comfy-core-enums.json was taken from " + fixtureVer +
    ", so the template enum check is testing against a build a buyer no " +
    "longer gets. Re-harvest: " + REHARVEST;
}

module.exports = { FIXTURE, parseVersionPy, installedVersion,
                   fixtureVersion, driftNote, REHARVEST };
